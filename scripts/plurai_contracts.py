"""Read the backend's contract constants instead of retyping them.

    import sys; sys.path.insert(0, str(REPO / 'scripts'))
    from plurai_contracts import contract, fallbacks, report_fallbacks

    STATUSES = contract('drifted_refusal_statuses', default=('failed', 'failure', 'refused'))
    ...
    report_fallbacks()   # once, before the process exits
    fallbacks()          # …or read them, for a consumer that is not a CLI

WHY THIS EXISTS. A constant retyped by hand in this repo is a fork of the backend's value unless
something compares the two, and a comment promising that review keeps them in step is not a
comparison. The consumers read each value from the vendored payload instead; the one remaining
literal per consumer is its fallback, and `cross-repo-parity.yml` compares the payload against the
backend on every run.

`scripts/contracts/contracts.json` is vendored from the backend's `GET /client-contracts`, which
serves each value off the same in-process symbol the backend's own code reads.
`scripts/dev/vendor_client_contracts.py` writes it and `--check` compares it; nothing here is
hand-edited.

THREE RULES, and each one is a decision worth knowing about:

1. DEFAULT ON ABSENCE, LOUDLY. A block missing from the vendored payload returns the caller's
   `default` — which is that consumer's existing literal, unchanged. That is what makes adoption
   safe one consumer at a time, and it is also the failure mode of a plugin talking to an OLDER
   backend, which is a real deployment and not a hypothetical: boxes carry pinned image digests
   and source overlays, so a box that predates a block exists right now. A fallback is never
   silent — `report_fallbacks()` prints every block that took one and `fallbacks()` RETURNS them,
   so a consumer that is a library rather than a CLI (nobody calls its `main`, nothing flushes a
   report) can still read the record and a test can assert it empty. A default that fires without
   saying so is the hand-mirror again, wearing this module's name.

2. VENDORED WINS A MISMATCH. `compare_live()` takes a payload read from a live route and, when it
   differs, PRINTS the divergence and keeps the vendored value. This is the opposite of
   `verify_policies.py`'s sandbox-namespace precedence, deliberately: there a live read is the
   FRESHER source and the snapshot is the stale risk. Here the likely live source is a deployed
   box on a pinned digest, so preferring it would silently drag consumers BACKWARDS to whatever
   that box was built from — and it would do it invisibly, since a value that merely went stale
   raises nothing. The vendored copy is the one CI compares against `main`; it is the one that has
   been checked.

3. NO FOURTH TIER. There is no hand-editable override. That is the tier this module removes.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

VENDORED = Path(__file__).resolve().parent / 'contracts' / 'contracts.json'

#: Every block that fell back to a caller default, name -> why. Module-level and additive so one
#: report at the end names all of them; a per-call print interleaved with real output is a print
#: nobody reads.
_FALLBACKS: dict[str, str] = {}

#: What `compare_live()` returns instead of the empty list when it could not compare AT ALL. It
#: is not a block name — no block is implicated — and that is the point: an empty list is the
#: answer for "every block agrees", and a live read carrying no `blocks` at all was returning it.
#: A caller testing `if compare_live(...)` now sees a finding, and one that renders can recognise
#: this exact string rather than parsing the printed line.
NOTHING_COMPARED = '<the live read carried no contract blocks>'

#: Distinguishes "caller passed default=None" from "caller passed no default at all". A block a
#: consumer declares REQUIRED must raise, not resolve to None and fail somewhere else.
_REQUIRED = object()


class ContractsError(RuntimeError):
    """The vendored payload is missing or unusable, or a required block is absent.

    A plain exception, NOT SystemExit, because callers read contracts at MODULE SCOPE and a
    SystemExit there aborts the importing process — under pytest that is an INTERNALERROR and
    "no tests ran" for the whole session, rather than a collection error naming the file. Same
    reasoning as `verify_policies.VendoredNamespaceError`.
    """


def _load() -> dict[str, Any]:
    try:
        payload = json.loads(VENDORED.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise ContractsError(
            f'{VENDORED} is missing or unreadable ({exc}). It is a checked-in artifact generated by '
            'scripts/dev/vendor_client_contracts.py; without it this process cannot tell a backend '
            'contract from a guess.'
        ) from exc
    blocks = payload.get('blocks')
    if not isinstance(blocks, dict) or not blocks:
        raise ContractsError(f'{VENDORED} carries no contract blocks. Re-run scripts/dev/vendor_client_contracts.py against a current source.')
    return payload


_PAYLOAD: dict[str, Any] | None = None


def payload() -> dict[str, Any]:
    """The whole vendored payload, loaded once."""
    global _PAYLOAD  # noqa: PLW0603 - a module-level cache of a checked-in file
    if _PAYLOAD is None:
        _PAYLOAD = _load()
    return _PAYLOAD


def block_names() -> list[str]:
    return sorted(payload()['blocks'])


def contract(name: str, default: Any = _REQUIRED) -> Any:
    """The value of one contract block, or ``default`` if this payload does not carry it.

    Pass the consumer's EXISTING literal as `default`. Adoption is then a change that cannot
    regress: on a payload that has the block the literal stops being consulted, and on one that
    does not the consumer keeps its own literal, and `report_fallbacks()` says so.

    Omit `default` only where there is no sensible literal to fall back to; the block is then
    required and its absence raises.
    """
    try:
        blocks = payload()['blocks']
    except ContractsError as exc:
        # THE ARTIFACT ITSELF is unreadable — a truncated checkout, a consumer copied out of the
        # plugin on its own, a packaging accident. A caller that declared a fallback gets it and
        # is TOLD, because the alternative is an exception at module scope in a customer's
        # session: the run has already happened and the aggregation dies rather than reporting
        # with the literals it has always had. A caller with no fallback still raises — it
        # declared that it cannot proceed on a guess.
        if default is _REQUIRED:
            raise
        _FALLBACKS[name] = f'the vendored payload could not be read ({exc})'
        return default
    entry = blocks.get(name)
    if isinstance(entry, dict) and 'value' in entry:
        return entry['value']
    if default is _REQUIRED:
        raise ContractsError(
            f'contract block {name!r} is not in {VENDORED.name} and the caller declared no fallback. '
            f'Known blocks: {", ".join(sorted(blocks))}. Re-vendor from a backend or a backend '
            'checkout that serves it.'
        )
    _FALLBACKS[name] = 'not served by the vendored payload'
    return default


def fallbacks() -> dict[str, str]:
    """Every block that fell back so far, name -> why. A COPY, so a reader cannot edit the record.

    `report_fallbacks()` helps only a consumer with a `main()` that calls it before exiting. A process
    that imports the consumer as a library would record fallbacks into a dict nobody reads, which is
    the silent default this module exists to remove. This is the readable form: a test asserts it
    empty (the vendor drift lane does), and a caller that renders can branch on it per block.
    """
    return dict(_FALLBACKS)


def report_fallbacks(stream: Any = None) -> list[str]:
    """Print every block that fell back, once. Returns the names, for a caller that tests this.

    Called at the END of a run rather than at each fallback, so the message is one block of text
    an operator can act on instead of a line lost in the middle of real output. Prints NOTHING
    when nothing fell back — a routine "all good" line is how a real warning gets scrolled past.
    """
    if not _FALLBACKS:
        return []
    out = stream or sys.stderr
    names = sorted(_FALLBACKS)
    print(
        f'NOTE(plurai-contracts): {len(names)} contract block(s) fell back to this repo\'s own literals: '
        f'{", ".join(names)}.',
        file=out,
    )
    # WHY each one fell back, not just that it did. "the block is not in this payload" (an older
    # backend) and "the payload could not be read at all" (a broken install) call for different
    # actions, and one line naming both as 'fell back' sends an operator to re-vendor when the
    # artifact is the thing that is missing.
    for name in names:
        print(f'  {name}: {_FALLBACKS[name]}', file=out)
    print(
        '  The vendored payload does not carry them. That is expected against a backend older than '
        'the block (boxes run pinned image digests), and the local literals are being used instead — '
        'which is exactly the hand-mirrored copy that has drifted before. Re-run '
        'scripts/dev/vendor_client_contracts.py against a current source to stop guessing.',
        file=out,
    )
    return names


def compare_live(live: Any, stream: Any = None) -> list[str]:
    """Compare a payload read from the live route against the vendored copy.

    PREFERS THE VENDORED COPY — this function returns the divergence, it does not adopt anything.
    See rule 2 in the module docstring: the live source is usually a box on a pinned digest, so
    adopting it can move a consumer backwards silently, whereas the vendored copy is the one CI
    holds against the backend's main branch.

    Returns the names of every block the two sides do not agree on — a changed VALUE, or a block
    present on one side only — and prints them. An empty list means agreement.

    A block present on one side only is a divergence. A backend that predates a block is exactly the
    deployment that makes consumers fall back to their own literals, so the one comparison that can
    see it must not be silent about it. It is reported in its own two sections rather than as
    "differs", because a reader told a value changed goes looking for a changed value.
    """
    out = stream or sys.stderr
    vendored_blocks = payload()['blocks']
    live_blocks = live.get('blocks') if isinstance(live, dict) else None
    if not isinstance(live_blocks, dict):
        # NOT `[]`. That is the value this function returns when every block agrees, and a read
        # that carried no blocks agreed with nothing — a route that answered 200 with a body this
        # cannot parse, an error page, a proxy. Returning the agreement value for it is the same
        # collapse as `report_fallbacks` printing nothing: two states, one colour.
        print(
            'NOTE(plurai-contracts): NOTHING COMPARED — the live read carried no contract blocks '
            '(no `blocks` object in the payload). The vendored copy is unchanged and UNVERIFIED '
            'against this backend; check the route and the token before reading this as agreement.',
            file=out,
        )
        return [NOTHING_COMPARED]

    def canonical(value: Any) -> str:
        return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':'))

    diverged: list[str] = []
    only_live: list[str] = []
    only_vendored: list[str] = []
    for name in sorted(set(vendored_blocks) | set(live_blocks)):
        vendored_entry = vendored_blocks.get(name)
        live_entry = live_blocks.get(name)
        if live_entry is None:
            only_vendored.append(name)
            continue
        if vendored_entry is None:
            only_live.append(name)
            continue
        if canonical(vendored_entry.get('value')) != canonical(live_entry.get('value')):
            diverged.append(name)
    findings = sorted(diverged + only_live + only_vendored)
    if not findings:
        return []
    print(
        f'NOTE(plurai-contracts): {len(findings)} block(s) do not agree between this backend and '
        f'the vendored copy: {", ".join(findings)}. USING THE VENDORED VALUES.',
        file=out,
    )
    for name in diverged:
        print(f'  {name}: the VALUE differs', file=out)
        print(f'    backend:  {canonical(live_blocks[name].get("value"))[:200]}', file=out)
        print(f'    vendored: {canonical(vendored_blocks[name].get("value"))[:200]}', file=out)
    for name in only_live:
        print(
            f'  {name}: served by the BACKEND, absent from the vendored copy — every consumer of it '
            'is falling back to its own literal on this checkout.',
            file=out,
        )
    for name in only_vendored:
        print(
            f'  {name}: in the VENDORED copy, not served by this backend — the backend predates it '
            '(a pinned digest or an overlay), so nothing there is publishing that contract.',
            file=out,
        )
    print(
        '  The vendored copy wins because the backend may be a box on a pinned digest, and adopting '
        'a lagging value would move this run backwards without saying so. If the BACKEND is right, '
        're-run scripts/dev/vendor_client_contracts.py and commit; if it is behind, deploy it.',
        file=out,
    )
    return findings
